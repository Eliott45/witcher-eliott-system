export function equipmentTrait(label) {
  const normalized = label.toLocaleLowerCase().replaceAll("ё", "е").trim();
  if (/^сбалансированное\s*\(\+5\)/u.test(normalized)) return { label, description: "Сорвишапка: +5 вместо обычных +2 к броску 2d6 по таблице критического ранения (максимум 12). Для прицельного критического ранения — обычное правило 1d6 + 1." };
  const rule = RULES.find(([prefix]) => normalized === prefix || normalized.startsWith(`${prefix} `) || normalized.startsWith(`${prefix}:`));
  return { label, description: LABELS[label] ?? rule?.[1] ?? `Свойство предмета: ${label}. Дополнительные условия см. в описании предмета.` };
}

