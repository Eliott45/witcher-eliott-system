export function lifeEventModifiers(system) {
  if (system.details?.race === "witcher") return [];
  return (system.lifepath?.events ?? []).flatMap(event => {
    const base = { source: `life-event.${event.id}`, category: "lifepath" };
    if (event.kind === "fortune" && ["teacher", "instructor"].includes(event.fortune?.result) && event.fortune.skill)
      return [{ ...base, label: "Жизненный путь: обучение", target: event.fortune.skill.startsWith("language.") ? "skills.language" : `skills.${event.fortune.skill}`,
        ...(event.fortune.skill.startsWith("language.") ? { languageId: event.fortune.skill } : {}), value: Math.min(2, event.fortune.skillBonus || 1) }];
    if (event.kind === "misfortune" && event.misfortune?.result === "trauma" && event.misfortune.trauma === "poison")
      return [{ ...base, label: "Жизненный путь: отравление", target: "healthMax", value: -5 }];
    return [];
  });
}
